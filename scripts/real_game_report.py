"""The data part of docs/research/real-game-runs.md, from the real-game
bridge's records (results/real-game/<stamp>/, scripts/real_game.py).

    python scripts/real_game_report.py            # print it
    python scripts/real_game_report.py --write    # replace it in the doc

Runs are read from states.jsonl (one run per game seed), so a run whose
runs.jsonl line is missing still shows; its fights are fights.jsonl's lines
in order, a new run where the floor goes back down. The doc's hand-written
parts stay: only the text between the GENERATED markers is replaced."""

import argparse
import json
import os
import statistics
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECORDS = os.path.join(ROOT, "results", "real-game")
DOC = os.path.join(ROOT, "docs", "research", "real-game-runs.md")
# Run-layer rules versions (real_game_run.RUN_RULES) by the time their
# commit landed: 2 is 8d7d529a (below half HP, a rest site first).
RULES_FROM = {1: 0, 2: 1794640202, 3: 1794650779, 4: 1794651912, 5: 1794653235}
RULES_NOTE = {1: "fights before rest sites at any HP", 2: "below half HP a rest site first (8d7d529a)",
              3: "the map looks ahead to the next rest site",
              4: "rules 3, and event words match whole words",
              5: "rules 4, and elites last again"}
# The fighter's guard (real_game.FIGHT_GUARD): 1 from this time on, where a
# run's record doesn't say.
GUARD_FROM = 1794654136
GUARD_NOTE = "fight guard: a winning option the search passed is taken"
BEGIN, END = "<!-- GENERATED by scripts/real_game_report.py: don't edit by hand -->", "<!-- /GENERATED -->"


def lines(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as f:
        return [json.loads(x) for x in f if x.strip()]


def card(c):
    return c["id"].replace("_R", "") + "+" * c.get("upgrades", 0)


def runs_of(folder):
    """The runs in one record folder: per game seed, its states in order."""
    runs = {}
    for row in lines(os.path.join(folder, "states.jsonl")):
        gs = row["msg"].get("game_state")
        if not gs or gs.get("seed") is None:
            continue
        r = runs.setdefault(gs["seed"], {"seed": gs["seed"], "folder": os.path.basename(folder), "t0": row["t"],
                                         "hp": {}, "fights": [], "end": None})
        r["t1"] = row["t"]
        r["last"] = gs
        if r.get("ascension") is None and gs.get("ascension_level") is not None:
            r["ascension"] = gs["ascension_level"]
        r["combat"] = r.get("combat") or "combat_state" in gs
        if "combat_state" in gs:
            r["last_monsters"] = [m["id"] for m in gs["combat_state"].get("monsters", [])]
            hp = gs["combat_state"].get("player", {}).get("current_hp")
            if hp is not None:
                r.setdefault("fight_hp", {})[gs.get("floor")] = hp
        if gs.get("act") == 1 and "act1_boss" not in r:
            r["act1_boss"] = gs.get("act_boss")
        if gs.get("floor") is not None:
            r["hp"][gs["floor"]] = (gs.get("current_hp"), gs.get("max_hp"))
        if gs.get("screen_type") == "GAME_OVER":
            r["end"] = gs.get("screen_state", {})
    out = [r for r in runs.values() if r.get("last", {}).get("floor")]
    out.sort(key=lambda r: r["t0"])
    # fights.jsonl in order: a new run where the floor goes back down.
    fights, k, prev = lines(os.path.join(folder, "fights.jsonl")), -1, None
    with_fights = [r for r in out if r["combat"]]
    for f in fights:
        if prev is None or f["floor"] < prev:
            k += 1
        prev = f["floor"]
        if k < len(with_fights):
            r = with_fights[k]
            if "hp_after" not in f:
                # Records before eff55bc5: hp_end was the HP after the fight
                # (end-of-fight relics in); the HP in the fight's last state
                # comes from states.jsonl.
                f = dict(f, hp_after=f["hp_end"],
                         hp_end=r.get("fight_hp", {}).get(f["floor"], f["hp_end"]) if f["won"] else 0)
            r["fights"].append(f)
    # The run layer's rules version: from runs.jsonl where recorded, else
    # from when the controller started (the record folder's name) against
    # the commits that changed the rules.
    recorded = {x.get("seed"): x for x in lines(os.path.join(folder, "runs.jsonl"))}
    started = time.mktime(time.strptime(os.path.basename(folder)[:15], "%Y%m%d-%H%M%S"))
    for r in out:
        x = recorded.get(r["seed"], {})
        r["run_rules"] = x.get("run_rules") or max(v for v, t in RULES_FROM.items() if started >= t)
        r["fight_guard"] = x.get("fight_guard", 0) if x else int(started >= GUARD_FROM)
        r["commit"] = x.get("commit")
    return out


def all_runs(records=RECORDS):
    out = []
    for name in sorted(os.listdir(records)) if os.path.isdir(records) else []:
        folder = os.path.join(records, name)
        if os.path.isdir(folder) and name[:1].isdigit():
            out += [r for r in runs_of(folder) if r["fights"] or r["end"]]
    return out


def ending(r, newest=True):
    last = r["last"]
    if r["end"] is not None:
        if r["end"].get("victory"):
            return "won (score %s)" % r["end"].get("score")
        lost = [f["monsters"] for f in r["fights"] if not f["won"]] or [r.get("last_monsters")]
        where = (" to " + " + ".join(lost[-1])) if lost[-1] else ""
        return "died on floor %s%s (score %s)" % (last.get("floor"), where, r["end"].get("score"))
    if stopped(r):
        return "beat the Act 1 boss; stopped when Act 2 started (Act 2 isn't modelled, so it isn't played)"
    if not newest:
        return "stopped by a game restart on floor %s (the run was left)" % last.get("floor")
    return "not finished (floor %s)" % last.get("floor")


def fallback_reason(why):
    if why.startswith("monster ") and why.endswith(" not loaded"):
        return "monster not loaded (Act 2 and later)"
    return why


def after(f):
    """", 50 after the fight" where end-of-fight relics changed the HP."""
    return "" if f.get("hp_after") in (None, f["hp_end"]) else " (%s after)" % f["hp_after"]


def fmt_s(x):
    return "%.1f s" % x


def render(runs):
    out = [BEGIN, ""]
    if not runs:
        return "\n".join(out + ["No runs recorded yet.", "", END])
    fights = [f for r in runs for f in r["fights"]]
    modelled = [f for f in fights if f["predicted"]]
    out += ["Updated %s from %d record folders." % (time.strftime("%Y-%m-%d %H:%M"), len({r["folder"] for r in runs})), ""]
    out += ["## Summary", "", "One table per setting (ascension, the run layer's rules version and the fight guard): "
            "settings' numbers are never pooled.", ""]
    for st in sorted({setting(r) for r in runs}):
        out += summary([r for r in runs if setting(r) == st], st)
    out += ["## Runs", ""]
    return render_runs(runs, out, fights, modelled)


def stopped(r):
    """A run ended by choice when Act 2 started (real_game.py --act1-only)."""
    return r["end"] is None and (r["last"].get("act") or 1) >= 2


def asc(r):
    return r.get("ascension") or 0


def setting(r):
    """A run's setting: its ascension, the run layer's rules version and the
    fighter's guard (0 or 1)."""
    return asc(r), r.get("run_rules", 1), r.get("fight_guard", 0)


def setting_tag(r):
    """A run's setting in short: A20 r5, with g1 where the fight guard was on."""
    st = setting(r)
    return "A%d r%d%s" % (st[0], st[1], " g%d" % st[2] if st[2] else "")


def summary(runs, st):
    """The summary table of the runs at one ascension level."""
    fights = [f for r in runs for f in r["fights"]]
    pred = sum(f["predicted"] for f in fights)
    match = sum(f["matched"] for f in fights)
    think = [(t, r, f) for r in runs for f in r["fights"] for t in f["think_s"]]
    out = ["### Ascension %d, run rules %d (%s)%s" % (st[0], st[1], RULES_NOTE.get(st[1], ""),
                                                       ", %s" % GUARD_NOTE if st[2] else ""), "",
            "| | |", "|---|---|",
            "| Runs | %d (%d finished, %d of them stopped when Act 2 started) |" % (
                len(runs), sum(r["end"] is not None or stopped(r) for r in runs), sum(stopped(r) for r in runs)),
            "| Act 1 bosses beaten | %d |" % sum(any(f["group"] == "boss" and f["won"] and f["floor"] <= 17 for f in r["fights"]) for r in runs),
            "| Fights | %d (%d won), %d played by the engine to the end |" % (
                len(fights), sum(f["won"] for f in fights), sum(not f["handed_over"] for f in fights)),
            "| Fidelity | %d of %d chance-free steps matched the game (%.1f%%; steps with chance aren't compared) |" % (match, pred, 100.0 * match / max(pred, 1)),
            ]
    if think:
        worst = max(think, key=lambda x: x[0])
        out.append("| Decision time | median %s, worst %s (floor %s, %s) over %d decisions |" % (
            fmt_s(statistics.median(t for t, _, _ in think)), fmt_s(worst[0]), worst[2]["floor"],
            " + ".join(worst[2]["monsters"]), len(think)))
    out.append("")
    return out


def render_runs(runs, out, fights, modelled):
    for i, r in enumerate(runs, 1):
        last = r["last"]
        boss = [f for f in r["fights"] if f["group"] == "boss" and f["floor"] <= 17]
        act1 = [f for f in r["fights"] if f["floor"] <= 17 and f["hp_end"] is not None]
        out += ["### Run %d" % i, "",
                "- Seed %s, started %s (record folder `%s`)." % (r["seed"], time.strftime("%H:%M", time.localtime(r["t0"])), r["folder"]),
                "- Ascension %d, run rules %d%s%s. Reached floor %s (act %s); %s." % (
                    asc(r), setting(r)[1], ", fight guard %d" % setting(r)[2] if setting(r)[2] else "",
                    ", controller %s" % r["commit"] if r.get("commit") else "",
                    last.get("floor"), last.get("act"), ending(r, i == len(runs))),
                "- Act 1 boss: %s%s." % (r.get("act1_boss"), "" if not boss else ", %s, HP %s -> %s%s" % (
                    "beaten" if boss[0]["won"] else "lost", boss[0]["hp_start"], boss[0]["hp_end"], after(boss[0]))),
                "- HP at the end of each Act 1 fight (after it, where end-of-fight relics healed): "
                + ", ".join("F%d %s%s" % (f["floor"], f["hp_end"], "" if f["hp_after"] == f["hp_end"] else " (%s)" % f["hp_after"])
                            for f in act1) + ".",
                "- Deck at the end (%d): %s." % (len(last.get("deck", [])), ", ".join(card(c) for c in last.get("deck", []))),
                "- Relics at the end: %s." % ", ".join(x["id"] for x in last.get("relics", [])),
                ""]
    out += ["## Fights", "",
            "| Run | Setting | Floor | Kind | Monsters | HP | Result | Steps matched | Decisions | Think (median / worst) | Fallback |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(runs, 1):
        for f in r["fights"]:
            t = f["think_s"]
            out.append("| %d | %s | %d | %s | %s | %s -> %s%s | %s | %s | %d | %s | %s |" % (
                i, setting_tag(r), f["floor"], f["group"], " + ".join(f["monsters"]), f["hp_start"], f["hp_end"], after(f),
                "won" if f["won"] else "**lost**",
                "%d / %d" % (f["matched"], f["predicted"]) if f["predicted"] else "-", f["decisions"],
                "%s / %s" % (fmt_s(statistics.median(t)), fmt_s(max(t))) if t else "-",
                f["handed_over"] or ""))
    out.append("")
    reasons = {}
    for f in fights:
        if f["handed_over"]:
            reasons.setdefault(fallback_reason(f["handed_over"]), []).append(f["floor"])
    out += ["## Fallbacks", ""]
    out += ["- %s: %d fight(s), floors %s." % (k, len(v), ", ".join(map(str, v))) for k, v in sorted(reasons.items())] or ["None."]
    out += ["", "## Prediction misses", ""]
    misses = [(i, f, m) for i, r in enumerate(runs, 1) for f in r["fights"] for m in f["mismatches"]]
    out += ["- Run %d, floor %d (%s), turn %s: %s." % (i, f["floor"], " + ".join(f["monsters"]), m["turn"], ", ".join(m["keys"]))
            for i, f, m in misses] or ["None."]
    out += ["", "(%d of %d engine-played fights had no miss.)" % (sum(not f["mismatches"] for f in modelled), len(modelled)), "", END]
    return "\n".join(out)


def write(text, doc=DOC):
    with open(doc, encoding="utf-8") as f:
        old = f.read()
    a, b = old.find(BEGIN), old.find(END)
    if a < 0 or b < 0:
        raise SystemExit("%s has no GENERATED markers" % doc)
    with open(doc, "w", encoding="utf-8", newline="\n") as f:
        f.write(old[:a] + text + old[b + len(END):])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--records", default=RECORDS)
    a = ap.parse_args(argv)
    text = render(all_runs(a.records))
    if a.write:
        write(text)
    else:
        sys.stdout.write(text + "\n")


if __name__ == "__main__":
    main()
